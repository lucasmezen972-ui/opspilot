#!/usr/bin/env python3
"""Compile authored server-only programs and measured media into a seed migration.

The content/ directory is not imported by the Expo client. Graded answers remain
in the private server catalogue; the generated frontend file is an allowlist of
program metadata only. Run after rendering and reviewing every capsule.
"""
import argparse
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--media', type=Path, required=True)
parser.add_argument('--migration', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
sql, catalogue = ['-- Generated by scripts/build-training-programs.py; no learner answer-key access.\n'], []
for source in sorted((root / 'content/training-programs').glob('*.json')):
    p = json.loads(source.read_text())
    assert re.fullmatch(r'[a-z0-9-]{1,64}', p['key'])
    assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', p['version'])
    m = json.loads((args.media / p['key'] / 'manifest.json').read_text())
    assert p['key'] == m['key'] and p['version'] == m['version']
    assert re.fullmatch(r'[a-f0-9]{64}', m['sha256'])
    assert len(p['objectives']) >= 3 and len(p['chapters']) >= 3 and len(p['quiz']) >= 6
    assert all(len(c['body']) > 1000 for c in p['chapters'])
    assert m['size_bytes'] < 52428800 and m['duration_seconds'] > 60
    assert sum(q['question_type'] == 'situation' for q in p['quiz']) >= 1
    assert any(q['is_critical'] for q in p['quiz'])
    for q in p['quiz']:
        assert len(q['options']) >= 2 and 'correct_index' not in q and 'correct_indexes' not in q
    if not p.get('positioning'):
        p['positioning'] = ['Pouvez-vous expliquer la méthode à un collègue ?',
                            'Savez-vous reconnaître les limites de votre rôle ?',
                            'Connaissez-vous le relais de votre site ?']
    path = f'library/{p["version"]}/{p["key"]}/{m["sha256"]}.mp4'
    payload = json.dumps(p, ensure_ascii=False, separators=(',', ':'))
    manifest = json.dumps(m, ensure_ascii=False, separators=(',', ':'))
    assert '$program$' not in payload and '$media$' not in manifest
    sql.append(f"insert into opspilot_private.training_programs(program_key,version,payload,media_manifest,object_path) values('{p['key']}','{p['version']}',$program${payload}$program$::jsonb,$media${manifest}$media$::jsonb,'{path}') on conflict(program_key,version) do nothing;\n")
    meta = {k: p[k] for k in ['key','version','title','category','summary','audience',
        'prerequisites','requirement','applicability','onsite','objectives','positioning',
        'reading_minutes','activity_minutes','sources']}
    meta.update(video_seconds=m['duration_seconds'],video_chapters=m['chapters'],
        chapter_count=len(p['chapters']),quiz_count=len(p['quiz']),narration='synthetic',
        voice_model_card=m['voice_model_card'])
    catalogue.append(meta)
args.migration.write_text('\n'.join(sql))
(root / 'features/training/internalProgramCatalogue.json').write_text(
    json.dumps(catalogue, ensure_ascii=False, indent=2)+'\n')
print(f'{len(catalogue)} programs compiled; answer keys excluded from frontend metadata')
